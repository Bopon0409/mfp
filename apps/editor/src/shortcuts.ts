const TAB_KEY = 'mfp.shortcutsTab';

/**
 * Keyboard shortcuts panel at the bottom edge: tabs by section, doesn't get in the way of work —
 * no dimming. Ctrl+Shift+? again, Esc or the close button closes it; the tab is remembered.
 */
export function toggleShortcuts() {
  const old = document.getElementById('shortcuts');
  if (old) {
    old.remove();
    return;
  }
  let tab = 0;
  try {
    tab = Math.min(GROUPS.length - 1, Math.max(0, Number(localStorage.getItem(TAB_KEY)) || 0));
  } catch {
    /* first by default */
  }
  const box = document.createElement('div');
  box.id = 'shortcuts';
  box.setAttribute('role', 'dialog');
  box.setAttribute('aria-label', 'Сочетания клавиш');
  const tabs = document.createElement('div');
  tabs.className = 'sc-tabs';
  tabs.setAttribute('role', 'tablist');
  const body = document.createElement('div');
  body.className = 'sc-body';
  const close = document.createElement('button');
  close.className = 'sc-close';
  close.title = 'Закрыть (Esc)';
  close.textContent = '×';
  close.addEventListener('click', () => box.remove());
  const render = () => {
    tabs.replaceChildren(
      ...GROUPS.map(([title], k) => {
        const b = document.createElement('button');
        b.textContent = title;
        b.className = k === tab ? 'on' : '';
        b.setAttribute('role', 'tab');
        b.setAttribute('aria-selected', String(k === tab));
        b.addEventListener('click', () => {
          tab = k;
          try {
            localStorage.setItem(TAB_KEY, String(k));
          } catch {
            /* won't be remembered */
          }
          render();
        });
        return b;
      }),
      close,
    );
    const [, rows] = GROUPS[tab]!;
    body.innerHTML = rows.map(([k, d]) => `<div class="sc-row"><kbd>${k}</kbd><span>${d}</span></div>`).join('');
  };
  render();
  box.append(tabs, body);
  document.body.append(box);
}
